        private static JobHandle _readers;

        /// <summary>Zaregistruje job, který čte tabulky (volat z hlavního vlákna po Schedule).</summary>
        public static void TrackReader(JobHandle h) => _readers = JobHandle.CombineDependencies(_readers, h);

        /// <summary>Nahraje tabulky do NativeArray. Volat z hlavního vlákna před prvním jobem.</summary>
        public static void EnsureLoaded()
        {
            if (_ready) return;
#if UNITY_EDITOR
            // Bez tohohle Unity při reloadu skriptů hlásí neuvolněnou nativní kolekci.
            UnityEditor.AssemblyReloadEvents.beforeAssemblyReload -= Dispose;
            UnityEditor.AssemblyReloadEvents.beforeAssemblyReload += Dispose;
#endif
            UnityEngine.Application.quitting -= Dispose;
            UnityEngine.Application.quitting += Dispose;

            _tri = new NativeArray<sbyte>(TriTable, Allocator.Persistent);
            _owner = new NativeArray<sbyte>(EdgeOwner, Allocator.Persistent);
            _corners = new NativeArray<sbyte>(EdgeCorners, Allocator.Persistent);
            _cornerOffset = new NativeArray<sbyte>(CornerOffset, Allocator.Persistent);
            _ready = true;
        }

        public static NativeArray<sbyte> Tri          { get { EnsureLoaded(); return _tri; } }
        public static NativeArray<sbyte> Owner        { get { EnsureLoaded(); return _owner; } }
        public static NativeArray<sbyte> Corners      { get { EnsureLoaded(); return _corners; } }
        public static NativeArray<sbyte> CornerOffsets{ get { EnsureLoaded(); return _cornerOffset; } }

        /// <summary>Uvolní tabulky. Volá se při vypnutí aplikace.</summary>
        public static void Dispose()
        {
            if (!_ready) return;
            _readers.Complete();
            _readers = default;
            _tri.Dispose(); _owner.Dispose(); _corners.Dispose(); _cornerOffset.Dispose();
            _ready = false;
        }
